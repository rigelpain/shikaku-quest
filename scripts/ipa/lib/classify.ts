export interface ClassifyResult {
  major: Major;
  middle: Middle;
  score: number;
  candidates: Array<{ middle: Middle; score: number }>;
}

/**
 * 文章から中分類を推定する。
 * @param text 問題文 + 選択肢
 * @param majorHint 解答 PDF などから分かる大分類（AP 午前の T/M/S）
 * @param fallback 何もヒットしない場合の既定値
 */
export function classify(text: string, majorHint?: Major, fallback?: Middle): ClassifyResult {
  const scores = new Map<Middle, number>();
  for (const rule of RULES) {
    if (majorHint && majorOfMiddle(rule.middle) !== majorHint) continue;
    let s = 0;
    for (const re of rule.patterns) {
      const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g");
      const hits = text.match(g);
      if (hits) s += Math.min(hits.length, 6);
    }
    if (s > 0) scores.set(rule.middle, s * (rule.weight ?? 1));
  }
  const candidates = [...scores.entries()]
    .map(([middle, score]) => ({ middle, score }))
    .sort((a, b) => b.score - a.score);
  let middle: Middle;
  if (candidates.length) middle = candidates[0].middle;
  else if (fallback) middle = fallback;
  else if (majorHint === "マネジメント系") middle = "プロジェクトマネジメント";
  else if (majorHint === "ストラテジ系") middle = "企業活動";
  else middle = "基礎理論";
  return { major: majorOfMiddle(middle), middle, score: candidates[0]?.score ?? 0, candidates };
}
